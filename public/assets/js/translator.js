let originalNodes = new Map();

function translateDOM(targetLang) {
  const isEnglish = targetLang === 'en';

  function processNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      let text = node.nodeValue;
      if (!text || !text.trim()) return;

      if (!originalNodes.has(node)) {
        originalNodes.set(node, text);
      }

      if (isEnglish) {
        let trimmed = text.trim();
        if (DICTIONARY[trimmed]) {
          node.nodeValue = text.replace(trimmed, DICTIONARY[trimmed]);
        } else {
          for (const [fr, en] of Object.entries(DICTIONARY)) {
            if (text.includes(fr)) {
              text = text.replaceAll(fr, en);
            }
          }
          node.nodeValue = text;
        }
      } else {
        if (originalNodes.has(node)) {
          node.nodeValue = originalNodes.get(node);
        }
      }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      if (['SCRIPT', 'STYLE', 'CODE', 'NOSCRIPT'].includes(node.tagName)) return;

      if (node.hasAttribute('placeholder')) {
        const ph = node.getAttribute('placeholder');
        if (isEnglish && DICTIONARY[ph]) node.setAttribute('placeholder', DICTIONARY[ph]);
        else if (!isEnglish && REVERSE_DICTIONARY[ph]) node.setAttribute('placeholder', REVERSE_DICTIONARY[ph]);
      }

      for (let child of node.childNodes) {
        processNode(child);
      }
    }
  }

  processNode(document.body);
  document.documentElement.lang = targetLang;
}

function setSiteLanguage(lang) {
  try {
    localStorage.setItem('jn_lang', lang);
  } catch (e) {}

  translateDOM(lang);

  // Update dropdown buttons style
  const frBtns = document.querySelectorAll('.lang-btn-fr');
  const enBtns = document.querySelectorAll('.lang-btn-en');
  const checkFrs = document.querySelectorAll('.lang-check-fr');
  const checkEns = document.querySelectorAll('.lang-check-en');

  if (lang === 'fr') {
    frBtns.forEach(b => {
      b.classList.add('bg-white/15', 'text-[#10b981]');
      b.classList.remove('text-slate-300');
    });
    enBtns.forEach(b => {
      b.classList.remove('bg-white/15', 'text-[#10b981]');
      b.classList.add('text-slate-300');
    });
    checkFrs.forEach(c => c.classList.remove('hidden'));
    checkEns.forEach(c => c.classList.add('hidden'));
  } else {
    enBtns.forEach(b => {
      b.classList.add('bg-white/15', 'text-[#10b981]');
      b.classList.remove('text-slate-300');
    });
    frBtns.forEach(b => {
      b.classList.remove('bg-white/15', 'text-[#10b981]');
      b.classList.add('text-slate-300');
    });
    checkEns.forEach(c => c.classList.remove('hidden'));
    checkFrs.forEach(c => c.classList.add('hidden'));
  }

  // Toast notification feedback
  const msg = lang === 'en' ? '🇬🇧 Site translated to English!' : '🇫🇷 Site en version française !';
  if (typeof showToast === 'function') {
    showToast(msg);
  }
}

